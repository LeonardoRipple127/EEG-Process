function rejectIC = plotInteractiveICReview(EEG, freqRange)
% plotInteractiveICReview
% Interactive ICA review with ICLabel annotations.
%
% Click a component map or its title to open the native EEGLAB
% component-properties window (topography, activity and spectrum).
%
% No ICA decomposition is performed by this function.
% Components are not removed automatically.

    if nargin < 2 || isempty(freqRange)
        freqRange = [1 30];
    end

    assert(~isempty(EEG.icaweights) && ...
           ~isempty(EEG.icasphere) && ...
           ~isempty(EEG.icawinv), ...
        'The EEG dataset does not contain ICA decomposition.');

    assert(isfield(EEG, 'etc') && ...
           isfield(EEG.etc, 'ic_classification') && ...
           isfield(EEG.etc.ic_classification, 'ICLabel'), ...
        'ICLabel results are missing. Run pop_iclabel first.');

    classProb = EEG.etc.ic_classification.ICLabel.classifications;

    classNames = { ...
        'Brain', 'Muscle', 'Eye', 'Heart', ...
        'LineNoise', 'ChannelNoise', 'Other'};

    nIC = size(EEG.icawinv, 2);

    assert(size(classProb, 1) == nIC && ...
           size(classProb, 2) == 7, ...
        'ICLabel classification dimensions do not match ICA.');

    if isfield(EEG, 'icachansind') && ...
            ~isempty(EEG.icachansind)
        chanlocs = EEG.chanlocs(EEG.icachansind);
    else
        chanlocs = EEG.chanlocs;
    end

    assert(numel(chanlocs) == size(EEG.icawinv, 1), ...
        'ICA channel locations do not match the ICA decomposition.');

    %% Create overview using ordinary subplot, not tiledlayout
    nCols = ceil(sqrt(nIC));
    nRows = ceil(nIC / nCols);

    overviewFig = figure( ...
        'Color', 'w', ...
        'Name', 'Interactive ICA Component Review', ...
        'NumberTitle', 'off', ...
        'Units', 'pixels', ...
        'Position', [30 40 1600 1100]);

    annotationText = sprintf( ...
        ['ICA Component Overview | %d ICs\n' ...
         'Click a component map or title to open its properties'], ...
        nIC);

    annotation(overviewFig, 'textbox', ...
        [0.05 0.955 0.90 0.035], ...
        'String', annotationText, ...
        'EdgeColor', 'none', ...
        'HorizontalAlignment', 'center', ...
        'FontSize', 13, ...
        'FontWeight', 'bold');

    %% Draw all component maps
    for ic = 1:nIC

        ax = subplot(nRows, nCols, ic, ...
            'Parent', overviewFig);

        axes(ax);

        [bestProb, bestClass] = max(classProb(ic, :));

        % Potential artifact categories.
        artifactClasses = [2 3 4 5 6];
        [artifactProb, artifactIndex] = max( ...
            classProb(ic, artifactClasses));

        artifactClass = artifactClasses(artifactIndex);

        if artifactProb >= 0.50
            labelText = sprintf( ...
                'IC %d | CHECK: %s %.0f%%', ...
                ic, classNames{artifactClass}, ...
                100 * artifactProb);

            labelColor = [0.85 0.05 0.05];

        elseif bestClass == 1 && bestProb >= 0.70
            labelText = sprintf( ...
                'IC %d | Brain %.0f%%', ...
                ic, 100 * bestProb);

            labelColor = [0.05 0.45 0.15];

        else
            labelText = sprintf( ...
                'IC %d | REVIEW: %s %.0f%%', ...
                ic, classNames{bestClass}, ...
                100 * bestProb);

            labelColor = [0.80 0.38 0.02];
        end

        % Draw the scalp map.
        topoplot( ...
            EEG.icawinv(:, ic), ...
            chanlocs, ...
            'electrodes', 'off', ...
            'maplimits', 'absmax');

        axis(ax, 'off');

        % Click the title to open the component properties.
        hTitle = title(ax, labelText, ...
            'FontSize', 8, ...
            'FontWeight', 'bold', ...
            'Color', labelColor, ...
            'Interpreter', 'none');

        set(hTitle, ...
            'ButtonDownFcn', ...
            @(src, evt) openICProperty(EEG, ic, freqRange));

        % Make the scalp-map graphics clickable as well.
        set(ax, ...
            'ButtonDownFcn', ...
            @(src, evt) openICProperty(EEG, ic, freqRange));

        children = findall(ax);
        children(children == ax) = [];

        for k = 1:numel(children)
            try
                set(children(k), ...
                    'HitTest', 'on', ...
                    'ButtonDownFcn', ...
                    @(src, evt) openICProperty( ...
                        EEG, ic, freqRange));
            catch
                % Some graphics objects do not support click callbacks.
            end
        end
    end

    %% Review instructions
    fprintf('\n========================================\n');
    fprintf('Interactive ICA review\n');
    fprintf('Total ICs: %d\n', nIC);
    fprintf('Red: potential artifact; inspect manually.\n');
    fprintf('Green: Brain probability >= 70%%.\n');
    fprintf('Orange: uncertain; inspect manually.\n');
    fprintf('Click a map or title to open EEGLAB properties.\n');
    fprintf('Close the overview when review is complete.\n');
    fprintf('========================================\n');

    % Wait for the overview window to be closed.
    % This avoids the uiwait/timercb error in your MATLAB setup.
    waitfor(overviewFig);

    %% Ask which components should be removed
    prompt = sprintf([ ...
        'Enter IC indices to remove, e.g. [3 4 8].\n' ...
        'Enter [] to retain all %d components: '], nIC);

    rejectIC = input(prompt);

    if isempty(rejectIC)
        rejectIC = [];
        fprintf('No components selected for removal.\n');
        return;
    end

    rejectIC = unique(rejectIC(:)');

    assert(all(isfinite(rejectIC)) && ...
           all(rejectIC == round(rejectIC)) && ...
           all(rejectIC >= 1 & rejectIC <= nIC), ...
        'Invalid IC indices.');

    fprintf('Selected ICs for removal: %s\n', ...
        mat2str(rejectIC));

end


function openICProperty(EEG, ic, freqRange)
% Open the native EEGLAB component-properties window.

    fprintf('Opening properties for IC %d...\n', ic);

    try
        pop_prop( ...
            EEG, ...
            0, ...
            ic, ...
            NaN, ...
            {'freqrange', freqRange});

    catch ME
        warning('Could not open IC %d properties: %s', ...
            ic, ME.message);
    end

end
